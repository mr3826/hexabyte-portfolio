#!/usr/bin/env node
/**
 * Re-lay the build output for Cloudflare Pages, without touching the AWS layout.
 *
 * `npm run build` (via scripts/prerender-head.mjs) stages prerendered route HTML
 * flat under `dist/__prerender/` and records the S3 keys in `dist/prerendered.json`,
 * because the CloudFront-on-S3-REST origin serves the extensionless key `products`
 * for the URL `/products`. Cloudflare Pages does not use S3 keys at all: its route
 * matcher serves `products.html` for `/products` natively, and — when the upload
 * contains no top-level `404.html` — serves `/index.html` (HTTP 200) for any path
 * that is not a static asset, which is exactly the SPA deep-link behavior the
 * CloudFront 403/404 → /index.html rewrite provides today.
 *
 * So this script only translates the existing output into that layout:
 *
 *   dist/__prerender/products            → dist/products.html          (then removed)
 *   dist/__prerender/case-studies__x     → dist/case-studies/x.html    (then removed)
 *   dist/prerendered.json                → consumed and removed
 *   (new) dist/_headers                  immutable cache for hashed assets
 *
 * The body of each file is untouched — only where it lives changes — so the SPA,
 * the baked per-route metadata, canonicals and OG tags are byte-identical to what
 * the AWS pipeline uploads.
 *
 * Run this ONLY from the Cloudflare workflow, after `npm run build`. The AWS
 * pipeline still needs `__prerender/` and `prerendered.json`, and `npm run build`
 * must keep producing them unchanged.
 */

import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const dist = join(root, 'dist');

const manifestPath = join(dist, 'prerendered.json');
const stageDir = join(dist, '__prerender');

if (!existsSync(manifestPath) || !existsSync(stageDir)) {
  console.error('pages-emit: dist/prerendered.json or dist/__prerender is missing — run `npm run build` first.');
  process.exit(1);
}

// Pages' SPA fallback (root served for unknown paths, HTTP 200 — the behavior
// production relies on for every deep link) only applies when no top-level
// 404.html is present. If one ever appears in dist, the fallback silently
// changes to a 404 page, so fail loudly instead.
if (existsSync(join(dist, '404.html'))) {
  console.error('pages-emit: dist/404.html exists — Pages would disable SPA fallback and 404 real deep links.');
  process.exit(1);
}

const manifest = JSON.parse(readFileSync(manifestPath, 'utf8'));
const emitted = [];

for (const { key, file } of manifest) {
  const src = join(dist, file);
  if (!existsSync(src)) {
    console.error(`pages-emit: manifest references missing file dist/${file} for route /${key}`);
    process.exit(1);
  }
  const destRel = `${key}.html`;
  const dest = join(dist, destRel);
  mkdirSync(dirname(dest), { recursive: true });
  // Copy, do not move: __prerender/ is removed as a whole below.
  writeFileSync(dest, readFileSync(src));
  emitted.push(destRel);
}

// Response headers for Pages (parsed from dist/_headers; not itself served).
// Pages already adds X-Content-Type-Options: nosniff, Referrer-Policy and ETag
// revalidation by default, which matches current CloudFront behavior for HTML.
// The one deliberate deviation from defaults mirrors the AWS cache table:
// hashed filenames in assets/ are immutable for a year.
// The noindex rules keep every *.pages.dev hostname out of search indexes so,
// once hexabyte.tech is connected, the Pages subdomain cannot become a
// duplicate-content copy of the canonical site (canonical tags point to the apex).
const project = process.env.CF_PAGES_PROJECT || 'hexabyte-portfolio';
writeFileSync(
  join(dist, '_headers'),
  [
    '# Generated by scripts/pages-emit.mjs — edit the script, not this file.',
    '# Hashed (immutable) asset filenames from the Vite build.',
    '/assets/*',
    '  Cache-Control: public, max-age=31536000, immutable',
    '',
    '# Keep pages.dev hostnames unindexed (the custom domain is the canonical host).',
    `https://${project}.pages.dev/*`,
    '  X-Robots-Tag: noindex',
    '',
    `https://*.${project}.pages.dev/*`,
    '  X-Robots-Tag: noindex',
    '',
  ].join('\n'),
  'utf8',
);

// Pages uploads everything in the output directory verbatim. The AWS staging
// files must not become public files on the Pages domain.
rmSync(stageDir, { recursive: true, force: true });
rmSync(manifestPath, { force: true });

console.log(
  `pages-emit: wrote ${emitted.length} route files for Cloudflare Pages (${emitted.join(', ')}) + _headers; removed __prerender/ and prerendered.json from the upload.`,
);
